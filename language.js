(function () {
  'use strict';
  const normalize = value => value.replace(/\s+/g, ' ').trim();
  const reverse = Object.fromEntries(Object.entries(TH_TRANSLATIONS).map(([en, ta]) => [ta, en]));
  let language = 'en';
  try { language = localStorage.getItem('thulasi-language') === 'ta' ? 'ta' : 'en'; } catch (_) {}
  const texts = new WeakMap();
  const attributes = new WeakMap();
  const watchedAttributes = ['aria-label', 'placeholder', 'alt', 'title'];
  let observer;
  window.thTranslate = value => language === 'ta' ? (TH_TRANSLATIONS[normalize(value)] || value) : value;
  window.thBuildEnquiry = (data, school) => {
    const course = window.thTranslate(String(data.get('course')));
    const name = String(data.get('name') || '').trim();
    const phone = String(data.get('phone') || '').trim();
    const question = String(data.get('message') || '').trim();
    return language === 'ta'
      ? `வணக்கம் ${window.thTranslate(school.name)},\n\n${course} குறித்து விசாரிக்க விரும்புகிறேன்.\n\nபெயர்: ${name}\nதொலைபேசி: ${phone}\n\n${question}`
      : `Hello ${school.name},\n\nI would like to enquire about ${course}.\n\nName: ${name}\nPhone: ${phone}\n\n${question}`;
  };
  function translateText(node) {
    const raw = node.nodeValue;
    if (!normalize(raw)) return;
    let record = texts.get(node);
    if (!record || raw !== record.last) {
      const key = normalize(raw);
      record = {original: reverse[key] && !TH_TRANSLATIONS[key] ? reverse[key] : key, last: raw,
        before: raw.match(/^\s*/)[0], after: raw.match(/\s*$/)[0]};
      texts.set(node, record);
    }
    const translated = language === 'ta' ? TH_TRANSLATIONS[record.original] : record.original;
    if (translated === undefined) return;
    const next = record.before + translated + record.after;
    if (node.nodeValue !== next) node.nodeValue = next;
    record.last = next;
  }
  function translateAttribute(element, attribute) {
    const raw = element.getAttribute(attribute);
    if (!raw) return;
    let records = attributes.get(element);
    if (!records) { records = {}; attributes.set(element, records); }
    let record = records[attribute];
    if (!record || record.last !== raw) {
      const key = normalize(raw);
      record = {original: reverse[key] && !TH_TRANSLATIONS[key] ? reverse[key] : key, last: raw};
      records[attribute] = record;
    }
    const next = language === 'ta' ? TH_TRANSLATIONS[record.original] : record.original;
    if (next === undefined) return;
    if (raw !== next) element.setAttribute(attribute, next);
    record.last = next;
  }
  function observe() {
    observer.observe(document.documentElement, {subtree: true, childList: true, characterData: true,
      attributes: true, attributeFilter: watchedAttributes});
  }
  function render() {
    observer?.disconnect();
    document.documentElement.lang = language;
    const walker = document.createTreeWalker(document.documentElement, NodeFilter.SHOW_TEXT, {
      acceptNode(node) {
        return node.parentElement?.closest('script,style,textarea,[translate="no"]')
          ? NodeFilter.FILTER_REJECT : NodeFilter.FILTER_ACCEPT;
      }
    });
    let node;
    while ((node = walker.nextNode())) translateText(node);
    document.querySelectorAll('[aria-label],[placeholder],[alt],[title]').forEach(element => {
      if (element.closest('[translate="no"]')) return;
      watchedAttributes.forEach(attribute => translateAttribute(element, attribute));
    });
    document.querySelectorAll('[data-language]').forEach(button => {
      button.setAttribute('aria-pressed', String(button.dataset.language === language));
    });
    const description = document.querySelector('meta[name="description"]');
    if (description) description.content = language === 'ta'
      ? 'துளசி டிரைவிங் ஸ்கூல் — ஓட்டுநர் பயிற்சித் திட்டங்களை அறிந்து உங்கள் கற்றல் பயணத்தைத் தொடங்குங்கள்.'
      : 'THULASI Driving School — explore driving lessons and plan your learning journey.';
    if (observer) observe();
  }
  function init() {
    document.querySelectorAll('[data-language]').forEach(button => {
      button.addEventListener('click', () => {
        language = button.dataset.language === 'ta' ? 'ta' : 'en';
        try { localStorage.setItem('thulasi-language', language); } catch (_) {}
        render();
      });
    });
    observer = new MutationObserver(render);
    render();
  }
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', init, {once: true});
  else init();
})();
